import AuraCore
import Foundation
@testable import AuraClipboard

/// Doble del pasteboard: cada "copia externa" sube el changeCount, como el real.
@MainActor private final class FakePasteboard: ClipboardPasteboard {
    var changeCount = 0
    var current = ClipboardRead()
    var written: [ClipboardContent] = []

    func external(_ r: ClipboardRead) { current = r; changeCount += 1 }
    func read() -> ClipboardRead { current }
    func write(_ content: ClipboardContent) -> Int { written.append(content); changeCount += 1; return changeCount }
}

@MainActor func runClipboardSuite(_ t: SelfCheck) {
    let pb = FakePasteboard()
    let s = ClipboardService(pasteboard: pb, limit: 3)

    // Sin cambio de changeCount no se lee nada; el contenido previo al inicio no se captura.
    s.poll()
    t.expect(s.items.isEmpty, "portapapeles: vacío al inicio")

    pb.external(ClipboardRead(string: "hola"))
    s.poll(); s.poll()
    t.expect(s.items.count == 1 && s.items[0].content == .text("hola"), "portapapeles: captura texto una sola vez")

    pb.external(ClipboardRead(string: " https://example.com/a "))
    s.poll()
    t.expect(s.items[0].content == .url(URL(string: "https://example.com/a")!), "portapapeles: texto con forma de URL es enlace")

    pb.external(ClipboardRead(string: "hola"))
    s.poll()
    t.expect(s.items.count == 2 && s.items[0].content == .text("hola"), "portapapeles: duplicado sube arriba sin repetirse")

    // Ocultos, transitorios y archivos de Finder se ignoran.
    for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                 "org.nspasteboard.AutoGeneratedType", "public.file-url"] {
        pb.external(ClipboardRead(types: [type], string: "secreto"))
        s.poll()
    }
    t.expect(!s.items.contains { $0.content == .text("secreto") }, "portapapeles: ignora contenido oculto/transitorio")

    // Imágenes: se admiten y se descartan las que superan el límite.
    pb.external(ClipboardRead(imageData: Data([1, 2, 3])))
    s.poll()
    t.expect(s.items[0].content == .image(Data([1, 2, 3])), "portapapeles: captura imagen")
    pb.external(ClipboardRead(imageData: Data(count: ClipboardService.maxImageBytes + 1)))
    s.poll()
    t.expect(s.items[0].content == .image(Data([1, 2, 3])), "portapapeles: imagen enorme ignorada")
    pb.external(ClipboardRead(string: "  \n "))
    s.poll()
    t.expect(s.items.count == 3, "portapapeles: texto en blanco ignorado")

    // Límite: se expulsa el más antiguo no fijado; lo fijado se queda.
    let oldest = s.items[2].id
    s.togglePin(oldest)
    pb.external(ClipboardRead(string: "uno")); s.poll()
    pb.external(ClipboardRead(string: "dos")); s.poll()
    t.expect(s.items.count == 3 && s.items.contains { $0.id == oldest }, "portapapeles: respeta el límite y conserva lo fijado")

    // Volver a copiar: escribe y no se duplica al sondear.
    let before = s.items.count
    let id = s.items[1].id
    s.copy(id)
    s.poll()
    t.expect(pb.written.count == 1 && s.items.count == before && s.items[0].id == id,
             "portapapeles: copiar reescribe y no duplica")

    s.remove(id)
    t.expect(!s.items.contains { $0.id == id }, "portapapeles: borrar uno")
    s.clear()
    t.expect(s.items.isEmpty, "portapapeles: vaciar")

    // Ciclo de vida del timer: start captura desde ese momento, stop cancela.
    pb.external(ClipboardRead(string: "antes"))
    s.start(); s.start()
    t.expect(s.isRunning, "portapapeles: iniciado")
    s.poll()
    t.expect(s.items.isEmpty, "portapapeles: lo previo al inicio no se captura")
    s.stop()
    t.expect(!s.isRunning, "portapapeles: detenido")

    t.expect(ClipboardRow.trimmed("a\n\n  b  \nc") == "a b c", "portapapeles: texto recortado a una línea")
}
