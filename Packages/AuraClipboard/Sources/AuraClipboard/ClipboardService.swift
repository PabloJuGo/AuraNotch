import AppKit
import Foundation
import Observation

public enum ClipboardContent: Equatable, Sendable {
    case text(String)
    case url(URL)
    /// Datos tal cual los dio el sistema (PNG/TIFF); se reescriben vía `NSImage`.
    case image(Data)
}

public struct ClipboardItem: Identifiable, Equatable, Sendable {
    public let id: UUID
    public var content: ClipboardContent
    public var date: Date
    public var pinned: Bool
}

/// Lectura puntual del pasteboard: tipos declarados y las representaciones que nos interesan.
public struct ClipboardRead: Sendable {
    public var types: Set<String>
    public var string: String?
    public var url: URL?
    public var imageData: Data?
    public init(types: Set<String> = [], string: String? = nil, url: URL? = nil, imageData: Data? = nil) {
        self.types = types; self.string = string; self.url = url; self.imageData = imageData
    }
}

/// Pasteboard inyectable para pruebas. `write` devuelve el `changeCount` resultante para reconocer la propia escritura.
@MainActor
public protocol ClipboardPasteboard: AnyObject {
    var changeCount: Int { get }
    func read() -> ClipboardRead
    func write(_ content: ClipboardContent) -> Int
}

@MainActor
public final class SystemPasteboard: ClipboardPasteboard {
    private let pb: NSPasteboard
    public init(_ pb: NSPasteboard = .general) { self.pb = pb }
    public var changeCount: Int { pb.changeCount }

    public func read() -> ClipboardRead {
        let types = Set((pb.types ?? []).map(\.rawValue))
        let string = pb.string(forType: .string)
        let url = pb.string(forType: .URL).flatMap(URL.init(string:))
        // Solo se lee la imagen (puede pesar MB) si no hay texto ni enlace.
        let image = (string == nil && url == nil) ? (pb.data(forType: .png) ?? pb.data(forType: .tiff)) : nil
        return ClipboardRead(types: types, string: string, url: url, imageData: image)
    }

    public func write(_ content: ClipboardContent) -> Int {
        pb.clearContents()
        switch content {
        case .text(let s): pb.setString(s, forType: .string)
        case .url(let u): pb.setString(u.absoluteString, forType: .string); pb.setString(u.absoluteString, forType: .URL)
        case .image(let d): if let img = NSImage(data: d) { pb.writeObjects([img]) }
        }
        return pb.changeCount
    }
}

/// Historial del portapapeles (solo memoria). NSPasteboard no notifica cambios y no hay API pública que lo
/// haga (solo `changeCount`), así que mientras el servicio está iniciado —es decir, módulo activo— un único
/// timer de baja frecuencia compara `changeCount`; `stop()` lo cancela y no queda nada en reposo.
@MainActor @Observable
public final class ClipboardService {
    public static let pollInterval: TimeInterval = 0.6
    public static let defaultLimit = 25
    /// Imágenes mayores se ignoran: el historial vive en RAM.
    public static let maxImageBytes = 8 * 1024 * 1024
    /// Marcas de la convención nspasteboard.org (gestores de contraseñas, autogenerado) y copias de archivos de Finder.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "public.file-url",
    ]

    /// Más reciente primero; los fijados no se expulsan.
    public private(set) var items: [ClipboardItem] = []
    public private(set) var isRunning = false
    public let limit: Int

    @ObservationIgnored private let pasteboard: ClipboardPasteboard
    @ObservationIgnored private let now: () -> Date
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange: Int

    public init(pasteboard: ClipboardPasteboard = SystemPasteboard(), limit: Int = ClipboardService.defaultLimit,
                now: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard; self.limit = limit; self.now = now
        lastChange = pasteboard.changeCount
    }

    public func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChange = pasteboard.changeCount  // lo copiado antes de activar el módulo no se captura
        let t = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = Self.pollInterval  // sin prisa: se agrupa con otros despertares del sistema
        timer = t
    }

    public func stop() {
        timer?.invalidate(); timer = nil
        isRunning = false
    }

    /// Un paso de sondeo (público para las pruebas, que no esperan al timer).
    public func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        let r = pasteboard.read()
        guard r.types.isDisjoint(with: Self.ignoredTypes), let content = Self.content(of: r) else { return }
        insert(content)
    }

    /// Vuelve a poner el elemento en el portapapeles sin duplicarlo en el historial.
    public func copy(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        lastChange = pasteboard.write(items[i].content)  // marca la escritura propia
        var item = items.remove(at: i); item.date = now()
        items.insert(item, at: 0)
    }

    public func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
    }

    public func remove(_ id: UUID) { items.removeAll { $0.id == id } }

    /// Vacía el historial, también lo fijado: es la acción explícita de borrar todo.
    public func clear() { items.removeAll() }

    private func insert(_ content: ClipboardContent) {
        var pinned = false
        if let i = items.firstIndex(where: { $0.content == content }) { pinned = items.remove(at: i).pinned }
        items.insert(ClipboardItem(id: UUID(), content: content, date: now(), pinned: pinned), at: 0)
        while items.count > limit, let last = items.lastIndex(where: { !$0.pinned }) { items.remove(at: last) }
    }

    static func content(of r: ClipboardRead) -> ClipboardContent? {
        func isWeb(_ u: URL) -> Bool { ["http", "https"].contains(u.scheme?.lowercased() ?? "") && u.host != nil }
        if let u = r.url, isWeb(u) { return .url(u) }
        if let s = r.string {
            let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
            if t.isEmpty { return nil }
            if !t.contains(where: \.isWhitespace), let u = URL(string: t), isWeb(u) { return .url(u) }
            return .text(s)
        }
        if let d = r.imageData, !d.isEmpty, d.count <= maxImageBytes { return .image(d) }
        return nil
    }
}
